"""Write docs/link-samples.md: Idealista links to check by hand.

Generates URLs only; it never requests idealista.pt.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd
import pyogrio
import shapely

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_shapes import CAOP_GPKG, make_shape  # noqa: E402
from polyline import encode, municipality_url, polygon_url  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
QUALITY = ROOT / "data/processed/shapes_quality.csv"
SHAPES = ROOT / "web/public/data/shapes.json"
OUT = ROOT / "docs/link-samples.md"


def main() -> None:
    quality = pd.read_csv(QUALITY, dtype={"dicofre": str})
    shapes = json.loads(SHAPES.read_text(encoding="utf-8"))
    gdf = pyogrio.read_dataframe(CAOP_GPKG, layer="cont_freguesias", columns=["dtmnfr", "freguesia", "municipio"])
    gdf = gdf[gdf.dtmnfr.isin(set(quality.dicofre))].copy()
    gdf["raw_vertices"] = shapely.get_num_coordinates(gdf.geometry.values)

    # The most detailed PNCT parish (most full-resolution vertices) that sits at the cap.
    capped = set(quality[quality.points == quality.points.max()].dicofre)
    big = gdf[gdf.dtmnfr.isin(capped)].sort_values("raw_vertices", ascending=False).iloc[0]
    by_cap = {n: make_shape(big.geometry, n) for n in (60, 100, 150)}

    hull = quality[quality.method == "hull"].sort_values("overreach_ratio", ascending=False).iloc[0]
    land = quality[quality.method == "single"].sort_values("coverage", ascending=False).iloc[0]

    def shape_of(dicofre: str) -> str:
        return shapes[dicofre]["shape"]

    lines = [
        "# Idealista link samples (manual check)",
        "",
        "Generated by `scripts/link_samples.py` from `web/public/data/shapes.json` and the same encoder the app uses.",
        "None of these URLs were requested by any script. Open each one in a browser and note what you see.",
        "",
        "For every polygon link, expect the Idealista map view with a drawn area that matches the parish.",
        "Compare it with the parish on the PNCT map.",
        "",
        "## 0. Control: a captured URL (known to work)",
        "",
        "Fixture 1 from the brief, rebuilt by our encoder. It should open exactly like the original capture.",
        "",
        f"- [comprar terrenos, urbanizável]({polygon_url('comprar', 'terrenos', encode([(37.94486, -7.90582), (38.07957, -7.88316), (38.08849, -7.67339), (37.92753, -7.68712), (37.94486, -7.90582)]), ['terreno-urbanizavel'])})",
        "",
        "## 1. Vertex limit",
        "",
        f"**Parish:** {big.freguesia} ({big.municipio}, `{big.dtmnfr}`).",
        f"Of the parishes at the {quality.points.max()}-vertex cap, this one has the most detailed full-resolution outline, with {big.raw_vertices:,} vertices.",
        "",
        "Shape detail at each cap:",
        "",
        "| Cap | Ring points | Simplification tolerance | Link |",
        "|---|---|---|---|",
    ]
    for n, s in by_cap.items():
        lines.append(f"| {n} | {s.points} | {s.tolerance_m:.0f} m | [comprar terrenos]({polygon_url('comprar', 'terrenos', encode(s.ring))}) |")
    lines += [
        "",
        "**What to check:**",
        "- Find the largest cap where Idealista still draws the full outline and shows results.",
        "- If 100 or 150 fails, possible symptoms are an error, an empty map, a truncated shape, or a redirect to a default area.",
        "- If 60 is the highest cap that works, keep `MAX_VERTICES = 60`. Otherwise tell me the new limit.",
        "",
        "## 2. Approximate (hull) parish",
        "",
        f"**Parish:** {hull.freguesia} ({hull.concelho}, `{hull.dicofre}`).",
        f"- It has {hull.parts} parts, so the search area is their convex hull.",
        f"- The hull covers 100% of the parish but adds {hull.overreach_km2:.1f} km² outside it, {hull.overreach_ratio:.0%} of the parish area.",
        "",
        f"- [comprar casas]({polygon_url('comprar', 'casas', shape_of(hull.dicofre))})",
        "",
        "**What to check:** the drawn area should cover both detached parts and the gap between them. Listings in the gap are false positives.",
        "",
        "## 3. Land filter \"Não urbanizável\" only (slug inferred)",
        "",
        f"**Parish:** {land.freguesia} ({land.concelho}, `{land.dicofre}`).",
        "",
        f"- [comprar terrenos, não urbanizável]({polygon_url('comprar', 'terrenos', shape_of(land.dicofre), ['terreno-nao-urbanizavel'])})",
        f"- [comprar terrenos, no filter (comparison)]({polygon_url('comprar', 'terrenos', shape_of(land.dicofre))})",
        "",
        "**What to check:**",
        "- The \"Não urbanizável\" filter should show as active in Idealista's filter panel, with fewer results than the unfiltered link.",
        "- If the filter is ignored, or the page errors or redirects, the `terreno-nao-urbanizavel` slug is wrong. Please note what Idealista's own URL shows when you tick that box.",
        "",
        "## 4. Municipality pages (slug rule unverified)",
        "",
        "Each concelho below is entirely PNCT.",
        "",
    ]
    for name in ("Castanheira de Pêra", "Vila Nova de Cerveira", "São João da Pesqueira"):
        lines.append(f"- {name}: [comprar terrenos]({municipality_url('comprar', 'terrenos', name)})")
    lines += [
        f"- Vila Nova de Cerveira with a land filter, in the guessed position: [comprar terrenos, urbanizável]({municipality_url('comprar', 'terrenos', 'Vila Nova de Cerveira', ['terreno-urbanizavel'])})",
        "",
        "**What to check:**",
        "- Each link should land on that municipality's listing page and not on a search or 404 page.",
        "- For the filtered link, check that the filter is active.",
        "- If a slug fails, note the slug Idealista actually uses, e.g. whether it adds a district suffix.",
        "",
        "## 5. Arrendar + terrenos (combination unverified)",
        "",
        f"- [arrendar terrenos, {land.freguesia}]({polygon_url('arrendar', 'terrenos', shape_of(land.dicofre))})",
        "",
        "**What to check:** a rental land search, which may legitimately have very few results. If Idealista redirects to another type, that combination isn't supported and the app should hide \"Arrendar\" for land.",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
