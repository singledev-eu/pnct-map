"""python -m insights <command>

  fetch [--refresh]        download INE and OSM sources into insights/data/raw/
  prepare                  build insights/data/prepared/ (sanity checks fail loudly)
  list                     every insight: ready/blocked, evergreen, posted, headline
  render --all | --id ID   write PNGs + captions to insights/out/<id>/ (offline)
  next [--dry-run]         pick the next unposted insight, render it, send it to Telegram, record it
"""

from __future__ import annotations

import argparse
import os
import sys

from insights import config as cfg

FRESH_AFTER = 2  # a fresh (non-evergreen) insight goes out after this many evergreen ones


def load_env() -> None:
    """.env (repo root, or INSIGHTS_ENV_FILE) without overriding variables already set."""
    from dotenv import load_dotenv

    load_dotenv(os.environ.get("INSIGHTS_ENV_FILE") or cfg.ENV_FILE, override=False)


def pick(ready: dict, posted: list[dict]):
    """Evergreen first, in catalog order, with a fresh one interleaved every FRESH_AFTER posts."""
    done = {e["id"] for e in posted}
    evergreen = [i for i in ready.values() if i.evergreen and i.id not in done]
    fresh = [i for i in ready.values() if not i.evergreen and i.id not in done]
    since_fresh = 0
    for e in reversed(posted):
        if not e.get("evergreen", True):
            break
        since_fresh += 1
    if fresh and (since_fresh >= FRESH_AFTER or not evergreen):
        return fresh[0]
    return evergreen[0] if evergreen else (fresh[0] if fresh else None)


def cmd_list() -> int:
    from insights import state
    from insights.catalog import compute_all

    ready, blocked = compute_all()
    posted = state.posted_ids()
    from insights.catalog import REGISTRY

    print(f"{'id':34} {'status':8} {'kind':9} {'posted':6}  headline")
    for iid, entry in REGISTRY.items():
        kind = "evergreen" if entry.evergreen else "fresh"
        if iid in ready:
            print(f"{iid:34} {'ready':8} {kind:9} {'yes' if iid in posted else 'no':6}  {ready[iid].chart_spec['headline']['en']}")
        else:
            print(f"{iid:34} {'blocked':8} {kind:9} {'—':6}  {blocked[iid].reason} (needs: {', '.join(blocked[iid].missing) or '—'})")
    print(f"\n{len(ready)} ready, {len(blocked)} blocked, {len(posted & set(ready))} posted")
    return 0


def cmd_render(all_: bool, iid: str | None) -> int:
    from insights.catalog import Data, compute, compute_all
    from insights.render import write_outputs

    data = Data()
    if all_:
        ready, blocked = compute_all(data)
        for ins in ready.values():
            print(f"rendered {write_outputs(ins, data)}")
        for b_id, b in blocked.items():
            print(f"blocked  {b_id}: {b.reason}")
        write_index(ready, blocked)
    else:
        print(f"rendered {write_outputs(compute(iid, data), data)}")
    return 0


def write_index(ready: dict, blocked: dict) -> None:
    lines = ["# PNCT Insights: rendered drafts", "", "Generated by `python -m insights render --all`.", ""]
    for ins in ready.values():
        lines += [f"## {ins.id} ({'evergreen' if ins.evergreen else 'fresh'})", "",
                  f"**{ins.chart_spec['headline']['en']}**: {ins.title}", "",
                  "EN:", "", "```", ins.caption_en, "```", "", "PT:", "", "```", ins.caption_pt, "```", ""]
    for b_id, b in blocked.items():
        lines += [f"## {b_id} (blocked)", "", f"{b.reason} Needs: {', '.join(b.missing)}", ""]
    cfg.OUT.mkdir(parents=True, exist_ok=True)
    (cfg.OUT / "INDEX.md").write_text("\n".join(lines), encoding="utf-8")


def cmd_next(dry_run: bool) -> int:
    from insights import state, telegram
    from insights.catalog import Data, compute_all
    from insights.render import write_outputs

    load_env()
    if not dry_run:
        try:
            token, chat = telegram.credentials()  # fail before doing any work
        except telegram.TelegramError as e:
            print(f"error: {e}", file=sys.stderr)
            return 2
    data = Data()
    ready, _ = compute_all(data)
    ins = pick(ready, state.load())
    if ins is None:
        print("nothing left to send: every ready insight is in posted.json")
        return 0
    out = write_outputs(ins, data)
    print(f"next: {ins.id} ({'evergreen' if ins.evergreen else 'fresh'}) → {out}")
    if dry_run:
        print(f"\n--- photo: {out / 'chart_en.png'}\n--- caption EN:\n{ins.caption_en}\n--- message PT:\n{ins.caption_pt}\n")
        print("dry run: nothing sent, posted.json unchanged")
        return 0
    try:
        photo_id = telegram.send_photo(token, chat, out / "chart_en.png", ins.caption_en)
        text_id = telegram.send_message(token, chat, ins.caption_pt)
    except telegram.TelegramError as e:
        print(f"error: {e}", file=sys.stderr)  # not recorded: the next run tries again
        return 1
    state.record(ins.id, ins.evergreen, message_ids=[photo_id, text_id])
    print(f"sent {ins.id} to Telegram and recorded it in {state.path()}")
    return 0


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(prog="python -m insights", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    f = sub.add_parser("fetch", help="download the sources")
    f.add_argument("--refresh", action="store_true")
    sub.add_parser("prepare", help="build the prepared tables")
    sub.add_parser("list", help="list insights")
    r = sub.add_parser("render", help="render PNGs and captions")
    g = r.add_mutually_exclusive_group(required=True)
    g.add_argument("--all", action="store_true")
    g.add_argument("--id")
    n = sub.add_parser("next", help="send the next insight to Telegram")
    n.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(argv)
    if a.cmd == "fetch":
        from insights.data.fetch import fetch

        fetch(a.refresh)
        code = 0
    elif a.cmd == "prepare":
        from insights.data.prepare import prepare

        prepare()
        code = 0
    elif a.cmd == "list":
        code = cmd_list()
    elif a.cmd == "render":
        code = cmd_render(a.all, a.id)
    else:
        code = cmd_next(a.dry_run)
    sys.exit(code)
